#!/usr/bin/env node
/* Catalogue data audit.
   Runs the same CatalogueModel.audit() the app's DATA AUDIT screen runs, straight
   from index.html, and writes docs/DATA_AUDIT.md.
   Usage:  node tools/audit.js            (writes docs/DATA_AUDIT.md)
           node tools/audit.js --check    (prints the totals only)          */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

function grab(re, what) { const m = html.match(re); if (!m) throw new Error('index.html: ' + what + ' not found'); return m[1]; }
const data = grab(/\nconst CATALOG_DATA = (\{.*?\});\n/, 'CATALOG_DATA');
const model = grab(/<script id="catalogue-model">([\s\S]*?)<\/script>/, 'catalogue-model script');
const imgLine = grab(/\nconst IMAGES_B64 = (\{.*?\});\n/, 'IMAGES_B64');
const imageKeys = Object.keys(JSON.parse(imgLine));
const brands = [...grab(/var MAISONS = \[([\s\S]*?)\];/, 'MAISONS').matchAll(/key:"(\w+)",\s*name:"([^"]+)"/g)].map(m => ({ key: m[1], name: m[2] }));

const ctx = {}; vm.createContext(ctx);
vm.runInContext('var CATALOG_DATA=' + data + ';\n' + model, ctx);
ctx.BRANDS = brands; ctx.IMAGE_KEYS = imageKeys;
const A = vm.runInContext('CatalogueModel.audit(CATALOG_DATA,BRANDS,IMAGE_KEYS)', ctx);
const DB = vm.runInContext('CALIBRE_DB', ctx), MK = vm.runInContext('MAKERS', ctx);
const T = A.totals;

if (process.argv.includes('--check')) { console.log(T); process.exit(0); }

const md = [];
const esc = s => String(s == null ? '' : s).replace(/\|/g, '\\|');
md.push('# Product catalogue audit', '',
  '_Generated by `node tools/audit.js` from `index.html`. The app’s **Catalogue → Data audit** screen runs the same code live._', '',
  '## Totals', '',
  '| | |', '|---|---:|',
  ['Brands', T.brands], ['References (SKUs)', T.products], ['Product models', T.models], ['Unique calibres', T.calibres],
  ['Automatic references', T.automatic], ['Quartz references', T.quartz], ['Manual-winding references', T.manual], ['Solar references', T.solar],
  ['References with missing calibre', T.missCalibre],
  ['References missing jewels', `${T.missJewels} (${T.missJewelsMech} automatic, ${T.missJewels - T.missJewelsMech} quartz)`],
  ['References missing power reserve (automatic)', T.missPR],
  ['Quartz references (battery-powered, power reserve not applicable)', `${T.quartzNoPR} (battery life known for ${T.quartzBattery})`],
  ['References missing movement type', T.missType], ['References missing case material', T.missMaterial],
  ['References with conflicting specifications', T.conflicts], ['References missing case thickness', T.missThickness],
  ['References missing weight', T.missWeight], ['Product photos with no product record', T.orphanImages]
);
for (let i = 0; i < md.length; i++) if (Array.isArray(md[i])) md[i] = '| ' + md[i][0] + ' | ' + md[i][1] + ' |';

md.push('', '## By brand', '',
  '| Brand | Products | Unique calibres | Missing jewels | Missing power reserve | Missing movement type | Missing material | Conflicting data |',
  '|---|---:|---:|---:|---:|---:|---:|---:|',
  ...A.rows.map(r => `| ${r.brand} | ${r.products} | ${r.calibres} | ${r.missJewels} | ${r.missPR}${r.quartzNoPR ? ` (+${r.quartzNoPR} quartz n/a)` : ''} | ${r.missType} | ${r.missMaterial} | ${r.conflicts} |`),
  '', '“Missing jewels” counts every quartz reference: none of the quartz listings state a jewel count. Quartz watches have no power reserve in the mechanical sense, so they are not counted as missing it.');

md.push('', '## Calibre database', '',
  '| Calibre | Manufacturer | Specification | Sub-dials | Type | Jewels | Power reserve | Used by |', '|---|---|---|---|---|---|---|---|');
const used = {}; A.products.forEach(p => p.calibreKeys.forEach(k => { (used[k] = used[k] || new Set()).add(p.brandName); }));
Object.keys(DB).sort((a, b) => a.localeCompare(b, undefined, { numeric: true })).forEach(k => {
  const d = DB[k], m = MK[d.maker] || {};
  md.push(`| ${k} | ${esc(m.name || 'Not specified')} | ${esc(d.spec.join(' · ') || 'Not specified')} | ${esc(d.layout.map(l => l[1] + 'H ' + l[0]).join(' · ') || '—')} | ${d.type} | ${d.jewels == null ? 'Not specified' : d.jewels} | ${d.powerReserve || (d.type === 'Quartz' ? 'n/a (battery)' : 'Not specified')} | ${[...(used[k] || [])].join(', ')} |`);
});

const SEV = { conflict: 'Conflicting specifications', review: 'Needs review', terminology: 'Terminology', missing: 'Missing specifications' };
for (const sv of Object.keys(SEV)) {
  md.push('', '## ' + SEV[sv], '');
  A.findings.filter(f => f.sev === sv).forEach(f => md.push(`- **${f.cat}.** ${f.msg}${f.refs.length ? ' References: ' + [...new Set(f.refs.map(p => p.ref))].join(', ') + '.' : ''}`));
  const groups = {};
  A.products.forEach(p => p.issues.filter(i => i[0] === sv).forEach(i => {
    const k = sv === 'missing' || sv === 'terminology' ? i[1].replace(/ \(listed as “[^”]*”\)/, '') : i[1];
    (groups[k] = groups[k] || []).push(p);
  }));
  Object.keys(groups).sort().forEach(k => md.push(`- ${k} — ${groups[k].length} reference${groups[k].length === 1 ? '' : 's'}: ${groups[k].map(p => `${p.ref} (${p.brandName} ${p.model})`).join(', ')}`));
}

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'DATA_AUDIT.md'), md.join('\n') + '\n');
console.log('docs/DATA_AUDIT.md written', T);
